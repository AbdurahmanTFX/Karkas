std::string project_id_from(std::string_view folder) {
  auto name = core::to_lower(std::string(folder));
  for (auto& c : name) {
    if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_')) c = '_';
  }
  if (name.empty() || !(name[0] >= 'a' && name[0] <= 'z')) return "";
  return name;
}

// The languages of the code already in the folder, most files first (ADR 0051). Build trees, vendored
// code and package caches do not count.
std::vector<std::string> code_languages(const fs::path& dir) {
  std::map<std::string, std::size_t> count;
  std::error_code ec;
  for (auto it = fs::recursive_directory_iterator(dir, fs::directory_options::skip_permission_denied, ec);
       !ec && it != fs::recursive_directory_iterator(); it.increment(ec)) {
    auto n = it->path().filename().string();
    if (it->is_directory(ec) && (n.starts_with(".") || core::is_build_dir(it->path()) || n == "third_party" || n == "_deps" ||
                                 n == "node_modules" || n == "vendor" || n == "venv" || n == "__pycache__" ||
                                 fs::exists(it->path() / "CACHEDIR.TAG", ec))) {
      it.disable_recursion_pending();
      continue;
    }
    if (!it->is_regular_file(ec)) continue;
    if (const auto* l = core::language_of(it->path())) ++count[l->id];
  }
  std::vector<std::string> out;
  for (const auto& l : core::languages()) {
    if (count.contains(l.id)) out.push_back(l.id);
  }
  std::stable_sort(out.begin(), out.end(), [&](const std::string& a, const std::string& b) { return count[a] > count[b]; });
  return out;
}

bool has_code(const fs::path& dir) { return !code_languages(dir).empty(); }

kk::Result<std::string> write_agent_guide(const fs::path& root) {
  constexpr std::string_view kBegin = "<!-- karkas:begin (generated by karkas gen guide; edit outside these marks) -->";
  constexpr std::string_view kBeginKey = "<!-- karkas:begin";
  constexpr std::string_view kEnd = "<!-- karkas:end -->";
  auto guide = target_template("karkas_guide.md");
  if (!guide) return std::unexpected(guide.error());
  std::string block = std::string(kBegin) + "\n" + *guide;
  if (!block.ends_with('\n')) block += '\n';
  block += std::string(kEnd) + "\n";
  auto path = root / "CLAUDE.md";
  std::error_code ec;
  if (!fs::exists(path, ec)) {
    if (auto r = core::write_file(path, block); !r) return std::unexpected(r.error());
    return std::string("created");
  }
  auto text = core::read_file(path);
  if (!text) return std::unexpected(text.error());
  std::string out;
  auto b = text->find(kBeginKey);
  auto e = b == std::string::npos ? std::string::npos : text->find(kEnd, b);
  if (b != std::string::npos && e != std::string::npos) {
    std::size_t after = e + kEnd.size();
    if (after < text->size() && (*text)[after] == '\n') ++after;
    out = text->substr(0, b) + block + text->substr(after);
  } else {
    out = *text;
    if (!out.empty() && !out.ends_with('\n')) out += '\n';
    if (!out.empty()) out += '\n';
    out += block;
  }
  if (out == *text) return std::string("unchanged");
  if (auto r = core::write_file(path, out); !r) return std::unexpected(r.error());
  return std::string("updated");
}

kk::Result<GenResult> write_claude_agents(const fs::path& root, const core::Config& cfg) {
  GenResult out;
  const fs::path dir = root / ".claude" / "agents";
  std::error_code ec;
  std::set<std::string> wanted;
  for (const auto& [tier, t] : cfg.models) {
    if (t.claude_model().empty()) continue;  // not a Claude model: Claude Code cannot run it
    auto name = core::subagent_name(tier);
    // Mode mcp: Karkas's agents do the work and a subagent only serves their turns — the two turn tools and
    // a short prompt, so a run costs its turns and nothing of a whole Claude Code tool set (token-cost-notes 5).
    auto text = target_template(cfg.mcp() ? "claude_agent_mcp.md" : "claude_agent.md",
                                {{"name", name}, {"tier", tier}, {"model", t.claude_model()}});
    if (!text) return std::unexpected(text.error());
    wanted.insert(name + ".md");
    auto path = dir / (name + ".md");
    auto rel = core::rel_str(root, path);
    if (fs::exists(path, ec)) {
      auto old = core::read_file(path);
      if (!old) return std::unexpected(old.error());
      if (!core::contains(*old, kGeneratedMarker)) {
        out.skipped.push_back(rel);
        continue;
      }
      if (*old == *text) {
        out.unchanged.push_back(rel);
        continue;
      }
    }
    if (auto r = core::write_file(path, *text); !r) return std::unexpected(r.error());
    out.written.push_back(rel);
  }
  // Subagents of tiers that are gone (or no longer Claude models).
  for (auto it = fs::directory_iterator(dir, ec); !ec && it != fs::directory_iterator(); it.increment(ec)) {
    auto n = it->path().filename().string();
    if (!n.starts_with("karkas-") || !n.ends_with(".md") || wanted.contains(n)) continue;
    auto old = core::read_file(it->path());
    if (!old || !core::contains(*old, kGeneratedMarker)) continue;
    fs::remove(it->path(), ec);
    out.removed.push_back(core::rel_str(root, it->path()));
  }
  std::ranges::sort(out.removed);
  return out;
}

kk::Result<std::string> claude_agents_json(const core::Config& cfg) {
  nlohmann::json out = nlohmann::json::object();
  for (const auto& [tier, t] : cfg.models) {
    if (t.claude_model().empty()) continue;
    auto name = core::subagent_name(tier);
    auto text = target_template("claude_agent.md", {{"name", name}, {"tier", tier}, {"model", t.claude_model()}});
    if (!text) return std::unexpected(text.error());
    // Front matter between the first two "---" lines; the rest is the prompt.
    auto end = text->find("\n---\n", 4);
    if (!text->starts_with("---\n") || end == std::string::npos) return kk::fail("templates", "claude_agent.md: no front matter");
    std::string description;
    for (const auto& line : core::split(text->substr(4, end - 4), '\n')) {
      if (!line.starts_with("description:")) continue;
      description = std::string(core::trim(line.substr(12)));
      if (description.size() >= 2 && description.front() == '"' && description.back() == '"') {
        description = description.substr(1, description.size() - 2);
      }
    }
    std::string prompt;
    for (const auto& line : core::split(text->substr(end + 5), '\n')) {
      if (core::contains(line, kGeneratedMarker)) continue;  // the note for people editing the file
      prompt += line + "\n";
    }
    out[name] = {{"description", description}, {"prompt", std::string(core::trim(prompt)) + "\n"}, {"model", t.claude_model()}};
  }
  return out.dump(2);
}

kk::Result<InitResult> init_project(const fs::path& root_in, std::string_view idea, ProjectKind kind) {
  fs::path root = core::normalize(root_in);
  InitResult out;
  out.name = project_id_from(root.filename().string());
  if (out.name.empty()) return kk::fail("init", "project folder name must start with a letter");
  std::error_code ec;
  if (fs::exists(root / "project.ksl", ec)) return kk::fail("init", root.string() + " already holds a project.ksl");
  fs::create_directories(root, ec);
  if (ec) return kk::fail("init", fmt::format("cannot create {}: {}", root.string(), ec.message()));
  // An existing project: keep its C++ standard and do not invent rules for its code.
  const auto langs = code_languages(root);
  out.existing_code = !langs.empty();
  out.langs = langs;
  if (kind == ProjectKind::Notes || (kind == ProjectKind::Auto && !out.existing_code && has_notes(root))) {
    // Notes (docs/adr/0038): the texts and their topics; nothing is built.
    out.notes = true;
    std::string project = fmt::format("@project {}\n", out.name);
    if (!idea.empty()) project += core::format_line("idea", core::format_free_text(idea)) + "\n";
    project += "lang    notes\n";
    if (auto r = core::write_file(root / "project.ksl", project); !r) return std::unexpected(r.error());
    out.written.push_back("project.ksl");
    // The models of the notes assistant (docs/adr/0039).
    if (!fs::exists(root / "karkas.toml", ec)) {
      if (auto r = core::write_file(root / "karkas.toml", std::string(target_template("karkas_notes.toml").value_or(""))); !r) {
        return std::unexpected(r.error());
      }
      out.written.push_back("karkas.toml");
    }
    fs::create_directories(root / "blocks", ec);
    if (auto r = index::ensure_karkas_dir(root); !r) return std::unexpected(r.error());
    auto imported = import_notes(root);
    if (!imported) return std::unexpected(imported.error());
    out.imported = imported->topics;
    out.imported.insert(out.imported.end(), imported->notes.begin(), imported->notes.end());
    return out;
  }
  std::string cxx = "20";
  if (auto cm = core::read_file(root / "CMakeLists.txt")) {
    std::smatch m;
    if (std::regex_search(*cm, m, std::regex(R"(CMAKE_CXX_STANDARD\s+(\d+))")) ||
        std::regex_search(*cm, m, std::regex(R"(cxx_std_(\d+))"))) {
      cxx = m[1].str();
    }
  }
  std::string project = fmt::format("@project {}\n", out.name);
  if (!idea.empty()) project += core::format_line("idea", core::format_free_text(idea)) + "\n";
  // The languages of the code there (C/C++ for a new project); the C++ build only where there is C++.
  const bool cpp = langs.empty() || std::find(langs.begin(), langs.end(), "cpp") != langs.end();
  project += core::format_line("lang", langs.empty() ? std::string("cpp") : core::join(langs, " ")) + "\n";
  if (cpp) project += fmt::format("build   cmake-ninja\nstd     c++{}\ntest    doctest\n", cxx);
  if (!out.existing_code) {
    project += "rule    blocks talk only through api/ headers\n"
               "rule    no exceptions across block boundaries, use Result<T>\n";
  }
  auto write = [&](const fs::path& p, std::string_view text) -> kk::VoidResult {
    if (p.empty() || fs::exists(p, ec)) return {};
    if (auto r = core::write_file(p, text); !r) return r;
    out.written.push_back(core::rel_str(root, p));
    return {};
  };
  auto toml = target_template("karkas.toml");
  if (!toml) return std::unexpected(toml.error());
  for (const auto& [path, text] : std::vector<std::pair<fs::path, std::string>>{
           {root / "project.ksl", project},
           {root / "karkas.toml", std::string(*toml)},
           {cpp ? root / "cmake" / "user.cmake" : fs::path(), std::string(target_template("user.cmake").value_or(""))},
           {root / ".gitignore", std::string(target_template("gitignore").value_or(""))}}) {
    if (auto r = write(path, text); !r) return std::unexpected(r.error());
  }
  // The guide for coding agents (Claude Code reads CLAUDE.md); an existing CLAUDE.md keeps
  // its text and gets the Karkas block appended.
  auto g = write_agent_guide(root);
  if (!g) return std::unexpected(g.error());
  if (*g != "unchanged") out.written.push_back("CLAUDE.md");
  // Subagents per model tier for Claude Code (karkas.toml merged with the user's config).
  auto cfg = core::load_config(root);
  if (!cfg) return std::unexpected(cfg.error());
  auto agents = write_claude_agents(root, *cfg);
  if (!agents) return std::unexpected(agents.error());
  out.written.insert(out.written.end(), agents->written.begin(), agents->written.end());
  fs::create_directories(root / "blocks", ec);
  fs::create_directories(root / "tests" / "integration", ec);
  if (auto r = index::ensure_karkas_dir(root); !r) return std::unexpected(r.error());
  return out;
}

